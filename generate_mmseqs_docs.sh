    "align"
    "alignall"
    "alignbykmer"
    "aliasdb"
    "apply"
    "besthitperset"
    "cluster"
    "clusterupdate"
    "clusthash"
    "clust"
    "combinepvalperset"
    "compress"
    "concatdbs"
    "convertalis"
    "convertmsa"
    "cpdb"
    "createdb"
    "createindex"
    "createlinindex"
    "createseqfiledb"
    "createsubdb"
    "createtaxdb"
    "createtsv"
    "db2tar"
    "decompress"
    "easy-cluster"
    "easy-linclust"
    "easy-linsearch"
    "easy-rbh"
    "easy-search"
    "easy-taxonomy"
    "expandaln"
    "extractorfs"
    "extractframes"
    "extractalignedregion"
    "filterdb"
    "filterresult"
    "filtertaxdb"
    "filtertaxseqdb"
    "gappedprefilter"
    "gpuserver"
    "kmermatcher"
    "kmersearch"
    "lca"
    "lcaalign"
    "linclust"
    "linsearch"
    "lndb"
