    "prefixid"
    "proteinaln2nucl"
    "rbh"
    "recoverlongestorf"
    "renamedbkeys"
    "rescorediagonal"
    "result2dnamsa"
    "result2flat"
    "result2msa"
    "result2profile"
    "result2rbh"
    "result2repseq"
    "result2stats"
    "reverseseq"
    "search"
    "setextendeddbtype"
